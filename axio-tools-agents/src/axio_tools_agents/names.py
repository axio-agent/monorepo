def generate_name(rng: random.Random | None = None) -> str:
    """One ``adjective_surname`` pair, drawn at random.

    Collisions are possible and harmless: an agent id carries a unique suffix of
    its own, and the name exists to be recognised, not to identify.
    """
    chooser = rng or random
    return f"{chooser.choice(ADJECTIVES)}_{chooser.choice(SURNAMES)}"


